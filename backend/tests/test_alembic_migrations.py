def _make_temp_db() -> Path:
    """Create a fresh SQLite file for a single test."""
    tmpdir = tempfile.mkdtemp(prefix="alembic_test_")
    return Path(tmpdir) / "test.db"


def _alembi_env(db_path: Path) -> dict:
    """Env vars that point alembic at the given SQLite file."""
    return {
        **os.environ,
        "DATABASE_URL": f"sqlite+aiosqlite:///{db_path}",
        "USE_SQLITE": "true",
        "FORCE_SQLITE": "true",
        "ANT_SKIP_ALEMBIC": "",  # ensure opt-out is off
    }


def _run_alembi(*args: str, env: dict) -> subprocess.CompletedProcess:
    return subprocess.run(
        [str(BACKEND_DIR / "venv" / "bin" / "alembic"), *args],
        cwd=str(BACKEND_DIR),
        env=env,
        capture_output=True,
        text=True,
        timeout=60,
    )


class TestAlembicCliOperations:
    """End-to-end: alembic upgrade / downgrade / current / stamp."""

    def setup_method(self):
        self.db_path = _make_temp_db()
        self.env = _alembi_env(self.db_path)

    def teardown_method(self):
        if self.db_path.exists():
            self.db_path.unlink()

    def _table_names(self) -> set:
        if not self.db_path.exists():
            return set()
        conn = sqlite3.connect(self.db_path)
        cur = conn.cursor()
        cur.execute("SELECT name FROM sqlite_master WHERE type='table'")
        names = {r[0] for r in cur.fetchall()}
        conn.close()
        return names

    def _alembi_version(self) -> str | None:
        conn = sqlite3.connect(self.db_path)
        cur = conn.cursor()
        try:
            cur.execute("SELECT version_num FROM alembic_version")
            row = cur.fetchone()
            return row[0] if row else None
        except sqlite3.OperationalError:
            return None
        finally:
            conn.close()

    def test_upgrade_head_creates_all_tables(self):
        result = _run_alembi("upgrade", "head", env=self.env)
        assert result.returncode == 0, (  # nosec B101
            f"alembic upgrade head failed:\nSTDOUT:{result.stdout}\nSTDERR:{result.stderr}"
        )
        names = self._table_names()
        # 13 model tables + alembic_version
        assert len(names) == 15  # nosec B101
        for tbl in (
            "users", "conversations", "voice_models", "job_applications",
            "interview_sessions", "analytics_events", "user_api_keys",
            "documents", "agent_sessions", "crm_configs", "integration_configs",
            "teams", "team_members", "audit_logs", "alembic_version",
        ):
            assert tbl in names  # nosec B101

    def test_upgrade_head_stamps_version_table(self):
        _run_alembi("upgrade", "head", env=self.env)
        version = self._alembi_version()
        assert version is not None  # nosec B101
        # Revision ID is 12 hex chars
        assert len(version) == 12  # nosec B101
        assert all(c in "0123456789abcdef" for c in version)  # nosec B101

    def test_upgrade_is_idempotent(self):
        # First upgrade
        r1 = _run_alembi("upgrade", "head", env=self.env)
        assert r1.returncode == 0  # nosec B101
        # Second upgrade should be a no-op (no migration runs)
        r2 = _run_alembi("upgrade", "head", env=self.env)
        assert r2.returncode == 0  # nosec B101
        # "Running upgrade" only appears in r1 (alembic logs to stderr)
        assert "Running upgrade" in r1.stderr  # nosec B101
        assert "Running upgrade" not in r2.stderr  # nosec B101

    def test_current_reports_head(self):
        _run_alembi("upgrade", "head", env=self.env)
        result = _run_alembi("current", env=self.env)
        assert result.returncode == 0  # nosec B101
        assert "head" in result.stdout  # nosec B101

    def test_history_lists_initial_migration(self):
        result = _run_alembi("history", env=self.env)
        assert result.returncode == 0  # nosec B101
        assert "initial schema" in result.stdout  # nosec B101

    def test_downgrade_base_drops_all_model_tables(self):
        _run_alembi("upgrade", "head", env=self.env)
        result = _run_alembi("downgrade", "base", env=self.env)
        assert result.returncode == 0, result.stderr  # nosec B101
        names = self._table_names()
        # Only `alembic_version` should remain after downgrade to base
        assert names == {"alembic_version"}  # nosec B101

    def test_roundtrip_upgrade_downgrade_upgrade(self):
        # Up → down → up: each step should succeed and the final state
        # should match the first upgrade.
        _run_alembi("upgrade", "head", env=self.env)
        tables_after_first = self._table_names()

        _run_alembi("downgrade", "base", env=self.env)
        _run_alembi("upgrade", "head", env=self.env)
        tables_after_re_upgrade = self._table_names()

        assert tables_after_first == tables_after_re_upgrade  # nosec B101


