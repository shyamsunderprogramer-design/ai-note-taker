class TestDatabaseManagerRunsAlembic:
    """DatabaseManager.initialize() applies alembic migrations automatically."""

    def setup_method(self):
        # Use a fresh temp dir + temp SQLite for the data dir.
        self.tmpdir = Path(tempfile.mkdtemp(prefix="dbmgr_alembic_"))
        self.tmp_db = self.tmpdir / "ainotetaker.db"
        # Point env vars at our temp DB. core.database reads DATABASE_URL,
        # USE_SQLITE, FORCE_SQLITE at import time, so we set them before
        # importing.
        os.environ["DATABASE_URL"] = f"sqlite+aiosqlite:///{self.tmp_db}"
        os.environ["USE_SQLITE"] = "true"
        os.environ["FORCE_SQLITE"] = "true"
        os.environ["ANT_SKIP_ALEMBIC"] = ""

    def teardown_method(self):
        # Clean env + files
        for var in ("DATABASE_URL", "USE_SQLITE", "FORCE_SQLITE"):
            if var in os.environ:
                del os.environ[var]
        os.environ.pop("ANT_SKIP_ALEMBIC", None)
        if self.tmp_db.exists():
            self.tmp_db.unlink()
        if self.tmpdir.exists():
            self.tmpdir.rmdir()

    def _init_db(self):
        import asyncio
        from core import database
        # Force the module to re-resolve its module-level DB URL from the
        # env vars we set in setup_method. This is safe because each test
        # creates a fresh tmpdir + tmp DB.
        database.DATABASE_URL = os.environ["DATABASE_URL"]
        database.USE_SQLITE = True
        database.FORCE_SQLITE = True
        asyncio.run(database.init_database())
        asyncio.run(database.close_database())

    def _table_names(self) -> set:
        if not self.tmp_db.exists():
            return set()
        conn = sqlite3.connect(self.tmp_db)
        cur = conn.cursor()
        cur.execute("SELECT name FROM sqlite_master WHERE type='table'")
        names = {r[0] for r in cur.fetchall()}
        conn.close()
        return names

    def _alembi_version(self) -> str | None:
        conn = sqlite3.connect(self.tmp_db)
        cur = conn.cursor()
        try:
            cur.execute("SELECT version_num FROM alembic_version")
            return cur.fetchone()[0]
        except sqlite3.OperationalError:
            return None
        finally:
            conn.close()

    def test_init_creates_all_tables(self):
        self._init_db()
        names = self._table_names()
        assert "users" in names  # nosec B101
        assert "conversations" in names  # nosec B101
        assert "audit_logs" in names  # nosec B101
        assert "alembic_version" in names  # nosec B101
        assert len(names) == 15  # nosec B101

    def test_init_stamps_alembic_version(self):
        self._init_db()
        version = self._alembi_version()
        assert version is not None  # nosec B101
        assert len(version) == 12  # nosec B101

    def test_init_is_idempotent(self):
        # First init
        self._init_db()
        tables_first = self._table_names()
        # Second init should not change anything
        self._init_db()
        tables_second = self._table_names()
        assert tables_first == tables_second  # nosec B101


class TestAntSkipAlembicOptOut:
    """ANT_SKIP_ALEMBIC=1 bypasses the alembic step (tests can opt out)."""

    def setup_method(self):
        self.tmpdir = Path(tempfile.mkdtemp(prefix="dbmgr_skip_"))
        self.tmp_db = self.tmpdir / "ainotetaker.db"
        os.environ["DATABASE_URL"] = f"sqlite+aiosqlite:///{self.tmp_db}"
        os.environ["USE_SQLITE"] = "true"
        os.environ["FORCE_SQLITE"] = "true"
        os.environ["ANT_SKIP_ALEMBIC"] = "1"

    def teardown_method(self):
        for var in ("DATABASE_URL", "USE_SQLITE", "FORCE_SQLITE"):
            if var in os.environ:
                del os.environ[var]
        os.environ.pop("ANT_SKIP_ALEMBIC", None)
        if self.tmp_db.exists():
            self.tmp_db.unlink()
        if self.tmpdir.exists():
            self.tmpdir.rmdir()

    def test_skip_alembic_does_not_create_version_table(self):
        import asyncio
        from core import database
        database.DATABASE_URL = os.environ["DATABASE_URL"]
        database.USE_SQLITE = True
        database.FORCE_SQLITE = True
        asyncio.run(database.init_database())
        asyncio.run(database.close_database())

        conn = sqlite3.connect(self.tmp_db)
        cur = conn.cursor()
        cur.execute("SELECT name FROM sqlite_master WHERE type='table'")
        names = {r[0] for r in cur.fetchall()}
        conn.close()

        # All 13 model tables still present (via create_all)
        assert "users" in names  # nosec B101
        assert "audit_logs" in names  # nosec B101
        # But no alembic_version table
        assert "alembic_version" not in names  # nosec B101


