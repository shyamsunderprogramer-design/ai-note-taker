class TestSecurityQuestionMigration:
    """Migration a1b2c3d4e5f6 adds `security_question` and
    `hashed_security_answer` to the users table. Runs alembic against
    a temp SQLite, asserts the columns exist post-upgrade, and
    confirms they are dropped on downgrade.

    The migration file is referenced by file path (not by name lookup)
    so this test continues to work even if the revision ID is
    regenerated by a future `alembic revision` run.
    """

    SECURITY_QUESTION_MIGRATION = (
        BACKEND_DIR / "migrations" / "versions" / "a1b2c3d4e5f6_add_security_question_columns.py"
    )

    def setup_method(self):
        assert self.SECURITY_QUESTION_MIGRATION.exists(), (
            f"Expected migration file missing: {self.SECURITY_QUESTION_MIGRATION}. "
            "Fix #35 Commit 1 should have created it."
        )
        self.db_path = _make_temp_db()
        self.env = _alembi_env(self.db_path)

    def teardown_method(self):
        if self.db_path.exists():
            self.db_path.unlink()

    def _column_names(self) -> set:
        """Return the set of column names on the users table."""
        if not self.db_path.exists():
            return set()
        conn = sqlite3.connect(self.db_path)
        cur = conn.cursor()
        cur.execute("PRAGMA table_info(users)")
        names = {row[1] for row in cur.fetchall()}
        conn.close()
        return names

    def _alembi_version(self) -> str | None:
        conn = sqlite3.connect(self.db_path)
        cur = conn.cursor()
        try:
            cur.execute("SELECT version_num FROM alembic_version")
            row = cur.fetchone()
            return row[0] if row else None
        except sqlite3.OperationalError:
            return None
        finally:
            conn.close()

    def test_upgrade_head_adds_security_question_columns(self):
        result = _run_alembi("upgrade", "head", env=self.env)
        assert result.returncode == 0, (  # nosec B101
            f"alembic upgrade head failed:\nSTDOUT:{result.stdout}\nSTDERR:{result.stderr}"
        )
        cols = self._column_names()
        assert "security_question" in cols  # nosec B101
        assert "hashed_security_answer" in cols  # nosec B101

    def test_upgrade_head_stamps_a1b2c3d4e5f6(self):
        result = _run_alembi("upgrade", "head", env=self.env)
        assert result.returncode == 0  # nosec B101
        version = self._alembi_version()
        # The migration chain is f78f0efa440e -> c391192d16be -> a1b2c3d4e5f6.
        # Head should land on a1b2c3d4e5f6.
        assert version == "a1b2c3d4e5f6"  # nosec B101

    def test_downgrade_one_step_drops_only_security_question_columns(self):
        _run_alembi("upgrade", "head", env=self.env)
        # Downgrade one step: c391192d16be -> a1b2c3d4e5f6 drop should remove
        # the two columns but leave the Fix #34 session columns intact.
        result = _run_alembi("downgrade", "-1", env=self.env)
        assert result.returncode == 0, result.stderr  # nosec B101
        cols = self._column_names()
        assert "security_question" not in cols  # nosec B101
        assert "hashed_security_answer" not in cols  # nosec B101
        # Fix #34 session columns are still present (c391192d16be is one rev back).
        assert "active_session_id" in cols  # nosec B101
        assert "on_new_login_pref" in cols  # nosec B101

    def test_roundtrip_upgrade_downgrade_upgrade(self):
        # Upgrade to head (a1b2c3d4e5f6) → downgrade one → upgrade to head.
        _run_alembi("upgrade", "head", env=self.env)
        cols_after_upgrade = self._column_names()
        _run_alembi("downgrade", "-1", env=self.env)
        _run_alembi("upgrade", "head", env=self.env)
        cols_after_re_upgrade = self._column_names()
        assert cols_after_upgrade == cols_after_re_upgrade  # nosec B101
        assert "security_question" in cols_after_re_upgrade  # nosec B101
        assert "hashed_security_answer" in cols_after_re_upgrade  # nosec B101


