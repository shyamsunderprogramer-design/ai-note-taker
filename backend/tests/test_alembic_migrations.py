"""
Test suite for the Alembic migration setup.

Covers:
- Migration file structure (upgrade/downgrade/revision identifiers).
- `alembic upgrade head` creates all 13 model tables + `alembic_version`.
- `alembic downgrade base` drops everything except the version table.
- Re-upgrade roundtrip works.
- Idempotency: running upgrade twice is a no-op (no new SQL emitted).
- `DatabaseManager.initialize` runs alembic and stamps the version table.
- `ANT_SKIP_ALEMBIC=1` bypasses alembic (legacy `create_all` path).
- `migrations/env.py` resolves the DB URL from env vars and imports the
  project's `Base.metadata` from `core.database` for autogenerate support.

Run with: python -m pytest backend/tests/test_alembic_migrations.py -v
"""

