class TestMigrationFileStructure:
    """The autogenerated migrations have the right shape."""

    def setup_method(self):
        # Locate the ROOT migration under versions/ (the one whose
        # `down_revision` is None). Multiple migrations can coexist
        # (e.g. f78f0efa440e → c391192d16be → a1b2c3d4e5f6); this
        # test class targets only the root, since that's the one
        # responsible for creating the 13 model tables.
        versions_dir = BACKEND_DIR / "migrations" / "versions"
        candidates = sorted(versions_dir.glob("*.py"))
        assert len(candidates) >= 1, "No migration files found in versions/"
        # Find the root migration: down_revision is None.
        root = None
        for path in candidates:
            text = path.read_text()
            if re.search(
                r"^down_revision:\s*Union\[str,\s*Sequence\[str\],\s*None\]\s*=\s*None",
                text, re.M,
            ):
                root = path
                break
        assert root is not None, "No root migration (down_revision=None) found"
        self.migration_file = root
        self.text = self.migration_file.read_text()

    def test_migration_has_revision_identifier(self):
        # `revision: str = '...'` line
        match = re.search(r"^revision:\s*str\s*=\s*'([a-f0-9]+)'", self.text, re.M)
        assert match is not None, "Migration has no `revision: str = '...'` line"  # nosec B101
        # Alembic revision IDs are 12 hex chars
        rev_id = match.group(1)
        assert len(rev_id) == 12  # nosec B101
        assert all(c in "0123456789abcdef" for c in rev_id)  # nosec B101

    def test_migration_is_root(self):
        # This is the FIRST migration, so down_revision must be None.
        match = re.search(
            r"^down_revision:\s*Union\[str,\s*Sequence\[str\],\s*None\]\s*=\s*None",
            self.text, re.M,
        )
        assert match is not None, "down_revision should be None for the initial migration"  # nosec B101

    def test_migration_has_upgrade_and_downgrade(self):
        assert "def upgrade() -> None:" in self.text  # nosec B101
        assert "def downgrade() -> None:" in self.text  # nosec B101

    def test_migration_creates_user_table(self):
        # users is the most critical table (every other table FKs into it).
        assert "op.create_table('users'" in self.text  # nosec B101
        # Required columns
        for col in ("'username'", "'email'", "'hashed_password'",
                    "'is_active'", "'is_admin'"):
            assert col in self.text, f"users table missing column {col}"  # nosec B101

    def test_migration_creates_all_13_model_tables(self):
        # Every model class in core.database has a __tablename__ — check
        # each one appears in a CREATE TABLE.
        expected_tables = [
            "users", "conversations", "voice_models", "job_applications",
            "interview_sessions", "analytics_events", "user_api_keys",
            "documents", "agent_sessions", "crm_configs", "integration_configs",
            "teams", "team_members", "audit_logs",
        ]
        for tbl in expected_tables:
            assert f"op.create_table('{tbl}'" in self.text, (  # nosec B101
                f"Migration does not CREATE TABLE for {tbl}"
            )

    def test_migration_creates_expected_indexes(self):
        # Spot-check a few critical indexes (FK columns + unique constraints).
        for idx in ("ix_users_username", "ix_users_email",
                    "ix_conversations_user_id", "ix_audit_logs_action",
                    "ix_job_applications_status"):
            assert idx in self.text, f"Missing index {idx}"  # nosec B101

    def test_migration_drops_all_tables_on_downgrade(self):
        # The downgrade path should call op.drop_table for every model table.
        expected_tables = [
            "users", "conversations", "voice_models", "job_applications",
            "interview_sessions", "analytics_events", "user_api_keys",
            "documents", "agent_sessions", "crm_configs", "integration_configs",
            "teams", "team_members", "audit_logs",
        ]
        for tbl in expected_tables:
            assert f"op.drop_table('{tbl}')" in self.text, (  # nosec B101
                f"downgrade() does not drop table {tbl}"
            )


